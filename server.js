import express from "express";
import cors from "cors";
import "dotenv/config";

const app = express();

const PORT = process.env.PORT || 3000;

const API_KEY = process.env.GEMINI_API_KEY;

const MODEL = process.env.GEMINI_MODEL || "gemini-3.5-flash-lite";

const FALLBACK_MODEL =
    process.env.GEMINI_FALLBACK_MODEL || "gemini-3.8-flash";

// CORS CONFIGURATION
const allowedOrigins = [
    "https://rajkushwahapvt-design.github.io",
    "http://127.0.0.1:5050",
    "http://localhost:5050",
    "http://127.0.0.1:5500",
    "http://localhost:5500"
];

app.use(cors({
    origin: (origin, callback) => {
        if (!origin || allowedOrigins.includes(origin)) {
            return callback(null, true);
        }

        return callback(new Error("Origin not allowed by CORS"));
    },
    methods: ["GET", "POST", "PUT", "DELETE", "OPTIONS"],
    allowedHeaders: ["Content-Type", "Authorization"]
}));

app.use(express.json({ limit: "1mb" }));

if (!API_KEY) {
    console.error("GEMINI_API_KEY is missing!");
    process.exit(1);
}

// HEALTH CHECK
app.get("/", (req, res) => {
    res.json({
        success: true,
        message: "AI Study Assistant Backend is running!"
    });
});

// WAIT FUNCTION
function wait(ms) {
    return new Promise(resolve => setTimeout(resolve, ms));
}

// GEMINI REQUEST FUNCTION
async function callGemini(prompt, model) {

    const response = await fetch(
        "https://generativelanguage.googleapis.com/v1beta/interactions",
        {
            method: "POST",
            headers: {
                "Content-Type": "application/json",
                "x-goog-api-key": API_KEY
            },
            body: JSON.stringify({
                model: model,
                input: prompt,
                store: false
            }),
            signal: AbortSignal.timeout(60000)
        }
    );

    const data = await response.json().catch(() => ({}));

    if (!response.ok) {
        const error = new Error(
            data.error?.message || "Gemini API request failed."
        );

        error.status = response.status;
        throw error;
    }

    const modelOutput = data.steps?.find(
        step => step.type === "model_output"
    );

    const generatedText =
        data.output_text ||
        modelOutput?.content
            ?.filter(item => item.type === "text")
            .map(item => item.text)
            .join("\n");

    if (!generatedText) {
        throw new Error("No text generated by Gemini.");
    }

    return generatedText;
}

// RETRY + FALLBACK SYSTEM
async function generateWithRetry(prompt, model) {

    const maxRetries = 3;

    for (let attempt = 1; attempt <= maxRetries; attempt++) {

        try {
            console.log(
                `Trying ${model} | Attempt ${attempt}/${maxRetries}`
            );

            const result = await callGemini(prompt, model);

            console.log(`Success using ${model}`);

            return result;

        } catch (error) {

            console.error(
                `Gemini error on attempt ${attempt}:`,
                error.message
            );

            const temporaryError =
                error.status === 503 ||
                error.status === 500 ||
                error.status === 429 ||
                error.name === "TimeoutError";

            if (!temporaryError || attempt === maxRetries) {
                throw error;
            }

            const delay = 2000 * Math.pow(2, attempt - 1);

            console.log(`Retrying after ${delay / 1000} seconds...`);

            await wait(delay);
        }
    }
}

// COMMON AI GENERATION ROUTE
app.post("/api/generate", async (req, res) => {

    try {

        const { prompt } = req.body;

        if (!prompt || typeof prompt !== "string" || !prompt.trim()) {
            return res.status(400).json({
                success: false,
                error: "Please provide a valid prompt."
            });
        }

        if (prompt.length > 30000) {
            return res.status(400).json({
                success: false,
                error: "Prompt is too long."
            });
        }

        let generatedText;
        let usedModel = MODEL;

        try {

            // First try primary model with retries.
            generatedText = await generateWithRetry(
                prompt,
                MODEL
            );

        } catch (primaryError) {

            console.error("Primary model failed:", primaryError.message);

            // Try fallback only for temporary failures.
            const canUseFallback =
                primaryError.status === 503 ||
                primaryError.status === 500 ||
                primaryError.status === 429 ||
                primaryError.name === "TimeoutError";

            if (!canUseFallback || FALLBACK_MODEL === MODEL) {
                throw primaryError;
            }

            console.log(`Switching to fallback model: ${FALLBACK_MODEL}`);

            usedModel = FALLBACK_MODEL;

            generatedText = await generateWithRetry(
                prompt,
                FALLBACK_MODEL
            );
        }

        return res.json({
            success: true,
            text: generatedText,
            model: usedModel
        });

    } catch (error) {

        console.error("Final Backend Error:", error);

        let statusCode = 500;
        let message = "Something went wrong on the server.";

        if (error.status === 429) {
            statusCode = 503;
            message =
                "Gemini API quota or rate limit reached. Please try again later.";

        } else if (error.status === 503) {
            statusCode = 503;
            message =
                "Gemini servers are temporarily overloaded. Please try again later.";

        } else if (error.status === 400 || error.status === 403) {
            statusCode = 502;
            message = error.message;

        } else if (error.name === "TimeoutError") {
            statusCode = 504;
            message = "AI request timed out. Please try again.";
        }

        return res.status(statusCode).json({
            success: false,
            error: message
        });
    }
});

// START SERVER
app.listen(PORT, () => {

    console.log(`Server running on port ${PORT}`);
    console.log(`Primary model: ${MODEL}`);
    console.log(`Fallback model: ${FALLBACK_MODEL}`);

});